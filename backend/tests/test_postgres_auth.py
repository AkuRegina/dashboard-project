"""PostgreSQL integration tests; the runner supplies an isolated test container."""
import os
from pathlib import Path
import unittest
import uuid

import psycopg
from psycopg import sql
from sqlalchemy.engine import make_url

import test_auth as unit_auth
from app import create_app, db
from app.demo import demo

TEST_URL = os.environ.get("POSTGRES_TEST_URL")
ROOT = Path(__file__).resolve().parents[2]
SCHEMA = (ROOT / "database/schema.sql").read_text(encoding="utf-8")
MIGRATION = (ROOT / "database/migrations/001_authentication.sql").read_text(encoding="utf-8")


def connect(schema=None):
    url = make_url(TEST_URL)
    return psycopg.connect(
        host=url.host, port=url.port, dbname=url.database,
        user=url.username, password=url.password, autocommit=True,
        options=f"-csearch_path={schema}" if schema else "",
    )


def create_schema():
    name = "auth_test_" + uuid.uuid4().hex
    with connect() as connection:
        connection.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(name)))
    return name


def drop_schema(name):
    # Only names generated by this test module may be removed.
    if not name.startswith("auth_test_") or len(name) != 42:
        raise ValueError("Invalid test schema name")
    with connect() as connection:
        connection.execute(sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(name)))


@unittest.skipUnless(TEST_URL, "Run python test_postgres.py to start an isolated PostgreSQL container")
class PostgreSQLAuthenticationTests(unit_auth.AuthenticationTests):
    def make_app(self):
        self.schema_name = create_schema()
        self.addCleanup(drop_schema, self.schema_name)
        url = make_url(TEST_URL).update_query_dict({"options": f"-csearch_path={self.schema_name}"})
        return create_app({
            "SQLALCHEMY_DATABASE_URI": url.render_as_string(hide_password=False),
            "TESTING": True,
            "RATELIMIT_ENABLED": False,
        })

    def initialize_database(self):
        with connect(self.schema_name) as connection:
            connection.execute(SCHEMA, prepare=False)
            connection.execute(MIGRATION, prepare=False)

    def cleanup_database(self):
        # The full schema (including views and deviation tables) is removed by addCleanup.
        pass

    def test_administrator_cli(self):
        result = self.app.test_cli_runner().invoke(args=[
            "create-admin", "--email", "cli@example.test", "--first-name", "CLI",
            "--last-name", "Admin", "--password", unit_auth.PASSWORD,
        ])
        self.assertEqual(result.exit_code, 0, result.output)
        headers, _ = self.login("cli@example.test")
        self.assertEqual(self.client.get("/auth/me", headers=headers).json["user"]["role"], "admin")

    def test_testpage_registration_login_and_logout(self):
        # Mount the local test interface for this test only; production stays unchanged.
        self.app.register_blueprint(demo)
        self.assertEqual(self.client.get("/").status_code, 200)
        response = self.client.post("/demo/register", json={
            "f_name": "Page", "l_name": "User", "email": "page@example.test",
            "password": unit_auth.PASSWORD, "role": "admin",
        })
        self.assertEqual(response.status_code, 201)
        self.assertEqual(response.json["user"]["role"], "worker")
        headers, _ = self.login("page@example.test")
        self.assertEqual(self.client.get("/auth/me", headers=headers).status_code, 200)
        self.assertEqual(self.client.post("/auth/logout", headers=headers).status_code, 204)
        self.assertEqual(self.client.get("/auth/me", headers=headers).status_code, 401)


@unittest.skipUnless(TEST_URL, "Run python test_postgres.py to start an isolated PostgreSQL container")
class PostgreSQLMigrationTests(unittest.TestCase):
    def setUp(self):
        self.schema_name = create_schema()
        self.addCleanup(drop_schema, self.schema_name)
        self.connection = connect(self.schema_name)
        self.addCleanup(self.connection.close)
        self.connection.execute(SCHEMA, prepare=False)

    def seed_user(self, email="legacy@example.test"):
        return self.connection.execute(
            "INSERT INTO users (f_name, l_name, email, password_hash) VALUES (%s, %s, %s, %s) RETURNING user_id",
            ("Legacy", "User", email, "placeholder"),
        ).fetchone()[0]

    def test_migration_preserves_users_deviations_comments_and_views(self):
        user_id = self.seed_user()
        severity_id = self.connection.execute("INSERT INTO severity (name) VALUES ('High') RETURNING severity_id").fetchone()[0]
        concern_id = self.connection.execute("INSERT INTO concern_types (name) VALUES ('Safety') RETURNING concern_type_id").fetchone()[0]
        deviation_id = self.connection.execute(
            "INSERT INTO deviations (concern_type_id, severity_id, description, submitted_by, assigned_to) "
            "VALUES (%s, %s, 'Existing deviation', %s, %s) RETURNING deviation_id",
            (concern_id, severity_id, user_id, user_id),
        ).fetchone()[0]
        self.connection.execute("INSERT INTO comments (deviation_id, user_id, comment_text) VALUES (%s, %s, 'Existing comment')", (deviation_id, user_id))
        self.connection.execute(MIGRATION, prepare=False)
        self.assertEqual(self.connection.execute("SELECT user_id, role, is_active FROM users").fetchone(), (user_id, "worker", True))
        self.assertEqual(self.connection.execute("SELECT description, submitted_by_name FROM deviation_details").fetchone(), ("Existing deviation", "Legacy User"))
        self.assertEqual(self.connection.execute("SELECT comment_text FROM comment_details").fetchone()[0], "Existing comment")

    def test_case_insensitive_email_index_and_role_constraint(self):
        self.seed_user()
        self.connection.execute(MIGRATION, prepare=False)
        with self.assertRaises(psycopg.errors.UniqueViolation):
            self.seed_user("LEGACY@example.test")
        with self.assertRaises(psycopg.errors.CheckViolation):
            self.connection.execute("UPDATE users SET role = 'invalid'")

    def test_conflicting_emails_roll_back_entire_migration(self):
        self.seed_user()
        self.seed_user("LEGACY@example.test")
        with self.assertRaises(psycopg.errors.UniqueViolation):
            self.connection.execute(MIGRATION, prepare=False)
        self.connection.execute("ROLLBACK")
        self.assertEqual(self.connection.execute("SELECT COUNT(*) FROM users").fetchone()[0], 2)
        columns = self.connection.execute(
            "SELECT column_name FROM information_schema.columns WHERE table_schema = %s AND table_name = 'users'",
            (self.schema_name,),
        ).fetchall()
        self.assertNotIn(("role",), columns)

    def test_session_foreign_key_and_user_deletion(self):
        user_id = self.seed_user()
        self.connection.execute(MIGRATION, prepare=False)
        with self.assertRaises(psycopg.errors.ForeignKeyViolation):
            self.connection.execute("INSERT INTO auth_sessions (token_hash, user_id, expires_at) VALUES (%s, %s, NOW() + INTERVAL '1 hour')", ("a" * 64, user_id + 100))
        self.connection.execute("INSERT INTO auth_sessions (token_hash, user_id, expires_at) VALUES (%s, %s, NOW() + INTERVAL '1 hour')", ("b" * 64, user_id))
        self.connection.execute("DELETE FROM users WHERE user_id = %s", (user_id,))
        self.assertEqual(self.connection.execute("SELECT COUNT(*) FROM auth_sessions").fetchone()[0], 0)
